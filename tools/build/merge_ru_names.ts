/**
 * Assemble modular_bandastation translation_data/ru_names.toml from per-entry TOML files.
 */

import {
  existsSync,
  mkdirSync,
  readFileSync,
  renameSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { dirname, relative } from 'node:path';
import {
  DEFAULT_FRAGMENTS_DIR,
  discoverFragments,
  REPO_ROOT,
  resolveCliPath,
} from './lib/ru_names';

const DEFAULT_OUTPUT = `${REPO_ROOT}/modular_bandastation/translations/code/translation_data/ru_names.toml`;

function runMerge(fragmentsRoot: string, outputPath: string): number {
  if (!existsSync(fragmentsRoot) || !statSync(fragmentsRoot).isDirectory()) {
    console.log(
      `No fragments directory at ${fragmentsRoot}; skipping merge (existing ${outputPath} unchanged).`,
    );
    return 0;
  }

  const discovered = discoverFragments(fragmentsRoot);
  if (discovered.length === 0) {
    console.log(
      `No *.toml under ${fragmentsRoot}; skipping merge (existing ${outputPath} unchanged).`,
    );
    return 0;
  }

  const sections: string[] = [
    '# ru_names.toml - generated by tools/build/merge_ru_names.ts',
    '# Do not edit this file directly.',
    '# Edit files under translation_data/ru_names/, then rebuild.',
    '',
  ];

  for (const fragmentPath of discovered) {
    const relPath = relative(fragmentsRoot, fragmentPath)
      .split(/[/\\]/)
      .join('/');
    const content = readFileSync(fragmentPath, 'utf-8').trimEnd();
    sections.push(`# ${relPath}`);
    sections.push(content);
    sections.push('');
  }

  const mergedText = `${sections.join('\n').trimEnd()}\n`;

  // Atomic write to a temp file then rename
  const tmpPath = `${outputPath}.tmp`;
  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(tmpPath, mergedText, { encoding: 'utf-8' });
  renameSync(tmpPath, outputPath);

  console.log(`Merged ${discovered.length} files into ${outputPath}.`);
  return 0;
}

function parseArgs(argv: string[]): { fragmentsDir: string; output: string } {
  let rawFragmentsDir: string | undefined;
  let rawOutput: string | undefined;

  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i]!;
    if (arg === '--fragments-dir' || arg === '--output') {
      if (!argv[i + 1]) {
        console.error(`Error: Missing value for ${arg}`);
        process.exit(2);
      }
      if (arg === '--fragments-dir') rawFragmentsDir = argv[++i]!;
      else rawOutput = argv[++i]!;
    } else {
      console.error(`Error: Unknown argument: ${arg}`);
      process.exit(2);
    }
  }

  return {
    fragmentsDir: resolveCliPath(rawFragmentsDir, DEFAULT_FRAGMENTS_DIR),
    output: resolveCliPath(rawOutput, DEFAULT_OUTPUT),
  };
}

function main(): number {
  const { fragmentsDir, output } = parseArgs(process.argv.slice(2));
  return runMerge(fragmentsDir, output);
}

process.exit(main());
